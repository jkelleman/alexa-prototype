// Prints transcripts for the shared scenarios, straight from the dialog engine.
//   node chat.js            -> print to the terminal
//   node chat.js --write    -> also write ../../design/transcripts.md
const fs = require('fs');
const path = require('path');
const FirstWords = require('./dialog');

function transcript(scenario) {
  const lines = [`## ${scenario.title}`, '', `_${scenario.blurb}_`, ''];
  let r = FirstWords.start();
  const note = (res) => (res.notes.length ? `  \n> <sub>${res.notes.map((n) => FirstWords.PRINCIPLES[n].label).join(' · ')}</sub>` : '');
  lines.push(`> **A:** ${r.say}${note(r)}`);
  for (const input of scenario.inputs) {
    const event = FirstWords.parse(input, r.state);
    lines.push('>', `> **U:** ${input || '_(silence)_'}`);
    r = FirstWords.next(r.state, event);
    lines.push('>', `> **A:** ${r.say || '_(session closes)_'}${note(r)}`);
    if (r.end) break;
  }
  lines.push('');
  return lines.join('\n');
}

const body = [
  '# Transcripts',
  '',
  'Generated by `skill/lambda/chat.js` from the same dialog engine the skill and the web demo use. Do not edit by hand; run `npm run transcripts`.',
  '',
  ...FirstWords.SCENARIOS.map(transcript),
].join('\n');

console.log(body);
if (process.argv.includes('--write')) {
  fs.writeFileSync(path.join(__dirname, '..', '..', 'design', 'transcripts.md'), body);
}
